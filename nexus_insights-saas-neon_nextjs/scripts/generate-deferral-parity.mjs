// Generates carbonless_backend/questionnaire/deferral_parity.json: the scenarios BOTH route engines (the JavaScript
// one in src/lib/carboniq/deferral.js and the Python one in questionnaire/deferral.py) must reproduce exactly —
// route, confirmed route, pending list, required-unanswered list and every deferral decision.
//   node scripts/generate-deferral-parity.mjs            writes the fixture
//   node scripts/generate-deferral-parity.mjs --check    fails when the committed fixture differs from what this generates
//
// Contents: 60 random partial answer sets (seeded, fixed), a route that AVOIDS each conditional question (121),
// every boundary value of every condition source (137), and 60 complete routes ending in the sign-off.
// Everything is deterministic (two fixed seeds) and is computed with the JavaScript engine, so the generated bytes
// depend only on the policy, the catalogue and the route audit. The Python test then proves the server engine agrees.
// If a legitimate change to the questionnaire or the policy changes the expected values, regenerate and review the diff.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(repoRoot, '..', 'carbonless_backend', 'questionnaire', 'deferral_parity.json');
const CHECK = process.argv.includes('--check');

// the catalogue, with its `@/` imports pointed at local copies (as the route audit and the policy generator do)
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'parity-gen-'));
const deps = { '@/lib/data/countries': 'src/lib/data/countries.js', '@/lib/utils/numbers': 'src/lib/utils/numbers.js', '@/lib/companyFields': 'src/lib/companyFields.js' };
let src = fs.readFileSync(path.join(repoRoot, 'src/lib/carboniq/questions.js'), 'utf-8');
for (const [alias, file] of Object.entries(deps)) {
  const local = `./${alias.split('/').pop()}.mjs`;
  src = src.replace(`'${alias}'`, `'${local}'`);
  fs.writeFileSync(path.join(scratch, local), fs.readFileSync(path.join(repoRoot, file), 'utf-8'));
}
fs.writeFileSync(path.join(scratch, 'questions.mjs'), src);
const { CARBONIQ_QUESTIONS } = await import(pathToFileURL(path.join(scratch, 'questions.mjs')));
const { createDeferral } = await import('../src/lib/carboniq/deferral.js');
const pol = JSON.parse(fs.readFileSync(path.join(repoRoot, '..', 'carbonless_backend', 'questionnaire', 'deferral_policy.json'), 'utf-8'));

// ── 1. the random partial answer sets (seed 20261102) ─────────────────────────────────────────────────────
const randomScenarios = (() => {
const e = createDeferral(pol); const Q = pol.questions;
let seed = 20261102; const rnd = () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
const pick = a => a[Math.floor(rnd() * a.length)];
const optVals = Object.fromEntries(CARBONIQ_QUESTIONS.map(q => [q.id, (q.options || []).map(o => o.value)]));
const SPECIAL = {
  B1: ['NACE_A', 'NACE_C', 'NACE_G'], C1: ['yes', 'no'], C3: ['yes', 'no'], D3: ['operational_control', 'financial_control', 'equity_share'],
  A7: ['yes', 'no', 'skip'], '3A-1': [['EQ-3A-01'], ['EQ-3A-99', 'EQ-3A-01']],
  '3A-5': [{ natural_gas: '1' }, { biomass: '5' }, { biomass: '' }], '3A-6': [{ x: 'engineering_estimate' }, { x: 'invoice_meter' }, { x: 'sector_average' }],
  '3B-5': [{ a: 'electric' }, { a: 'diesel' }], '3D-4': [{ a: { refill_kg: '0' } }, { a: { refill_kg: '5' } }, { a: { refill_kg: '' } }],
  '4A-1': [{ 1: '100 TL' }, { 1: '100 kWh' }], 'K3C7-1': [{ hybrid_count: '0' }, { hybrid_count: '5' }],
  'K3C7-3': [{ shuttle_pct: '0' }, { shuttle_pct: '10' }], '6F-1': [['none'], ['merger']],
  SCOPE: ['combined', 'separate'], A7a: ['2020'],
};
const val = (id) => {
  const q = Q[id];
  if (SPECIAL[id]) return pick(SPECIAL[id]);
  if (id === 'SCOPE-GROUPING') return pick(SPECIAL.SCOPE);
  if (q.nbv && q.type !== 'multi_select') return pick(Object.keys(q.nbv));
  if (optVals[id]?.length) return q.type === 'multi_select' ? [pick(optVals[id])] : pick(optVals[id]);
  return pick(['x', '5', 'text']);
};
const ids = Object.keys(Q).filter(i => Q[i].kind !== 'info');
const scenarios = [];
for (let s = 0; s < 150; s++) {
  const answers = {};
  const fill = rnd();               // from nothing answered to everything answered
  for (const id of ids) {
    if (rnd() < fill) { const v = val(id); answers[id] = rnd() < 0.5 ? { answer: v } : v; }
  }
  const pending = ids.filter(() => rnd() < 0.15);
  const route = e.routeIds(answers);
  scenarios.push({
    answers, pending, route, confirmed_route: e.routeIds(answers, { confirmed: true }),
    active_pending: e.activePending(pending, answers),
    required_unanswered: e.requiredUnanswered(answers),
    defer: Object.fromEntries(ids.filter(() => rnd() < 0.2).map(id => { const r = e.deferStatus(id, answers); return [id, r.ok ? 'ok' : r.code]; })),
  });
}
return scenarios;
})();

// ── 2. the witnesses: bypass, boundary and complete routes (seed 99) ───────────────────────────────────────
// (the route audit is loaded for its exhaustive search only: its own tests are skipped here)
process.env.AUDIT_CLASSES_ONLY = '1';
const A = await import('./audit-route-graph.mjs');
const D = await import('../src/lib/carboniq/deferral.js');
const POLICY = pol;
const out = (() => {
const eng = D.createDeferral(POLICY);
const data = { scenarios: JSON.parse(JSON.stringify({ scenarios: randomScenarios })).scenarios.slice(0, 60) };   // the first 60 random ones
const ids = Object.keys(POLICY.questions).filter(i => POLICY.questions[i].kind !== 'info');
let seed = 99; const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const A_DOMAIN = A.DOMAIN;
const compact = (m) => Object.fromEntries(Object.entries(m).filter(([k, v]) => A.DOMAIN[k] && v !== undefined));   // only the answers a condition or branch reads
const add = (kind, label, answers) => {
  const route = eng.routeIds(answers);
  const pending = ids.filter(() => rnd() < 0.2);
  data.scenarios.push({
    kind, label, answers, pending, route, confirmed_route: eng.routeIds(answers, { confirmed: true }),
    active_pending: eng.activePending(pending, answers), required_unanswered: eng.requiredUnanswered(answers),
    defer: Object.fromEntries(ids.filter(() => rnd() < 0.12).map(id => { const r = eng.deferStatus(id, answers); return [id, r.ok ? 'ok' : r.code]; })),
  });
};
// 1. a route that AVOIDS each question that is only sometimes on the route (the conditional ones)
for (const [id, w] of Object.entries(A.bypass)) if (w) add('bypass', id, compact(A.replayMap(w.path)));
// 3. every boundary value of every condition source, on an otherwise ordinary route
const base = {};
for (const [id, q] of Object.entries(POLICY.questions)) if (q.nbv && q.type !== 'info' && q.type !== 'section_picker' && q.type !== 'multi_select') base[id] = 'no' in q.nbv ? 'no' : Object.keys(q.nbv)[0];
base.A7 = 'no'; base['4A-0'] = 'yes'; base['3A-0'] = 'yes'; base['3B-0'] = 'yes'; base['SCOPE-GROUPING'] = 'combined';
for (const [v, dom] of Object.entries(A.DOMAIN)) for (const val of dom) add('boundary', `${v}=${JSON.stringify(val)}`, { ...base, [v]: val });
// 4. complete routes: every question the route shows is answered and the sign-off is "done" — the server must accept them
{
  const Q = POLICY.questions; let made = 0, guardTries = 0;
  while (made < 60 && guardTries++ < 5000) {
    let id = 'A1'; const A = {}; const seen = new Set(); const answered = {}; let last = null;
    for (let g = 0; id && g < 600; g++) {
      const q = Q[id]; if (!q || seen.has(id)) break;
      seen.add(id);
      if (q.show && !D.conditionalShowMatches(q.show, A)) { id = q.next || q.loopNext || null; continue; }
      if (q.type === 'section_picker') { id = q.next || null; continue; }
      last = id;
      const dom = A_DOMAIN[id]; const v = dom ? dom[Math.floor(rnd() * dom.length)] : undefined;
      if (dom) A[id] = v;
      if (q.type !== 'info') answered[id] = dom ? v : 'x';
      let next;
      if (q.loop) next = q.loopNext || q.next || null;
      else if (q.type === 'info') next = q.next || q.loopNext || (q.nbv ? Object.values(q.nbv).find(Boolean) : null) || null;
      else next = eng.nextQuestionId(q, v === undefined ? 'x' : v);
      if (next === '4-GİRİŞ' && A['SCOPE-GROUPING'] !== 'separate') next = Q['4-GİRİŞ']?.next || next;
      const backwards = (n) => !n || seen.has(n) || Q[n]?.type === 'section_picker';
      if (next && backwards(next)) { const alts = [q.next, ...Object.values(q.nbv || {}), q.loopNext]; next = alts.find(n => n && !backwards(n)) || null; }
      id = next;
    }
    if (last !== '7B-INFO' || answered['7B-INFO'] !== 'done') continue;       // keep only routes that end by signing off
    const scen = (() => { add('complete', 'route #' + made, answered); return data.scenarios.at(-1); })();
    if (scen.required_unanswered.length) throw new Error('a complete route leaves required questions unanswered: ' + scen.required_unanswered.join(','));
    made++;
  }
  console.log('complete routes generated:', made);
}

return data;
})();
const bytes = JSON.stringify(out);
if (CHECK) {
  const have = fs.readFileSync(FILE, 'utf-8');
  if (have !== bytes) { console.error('deferral_parity.json differs from what the generator produces; if the change is intended, run: node scripts/generate-deferral-parity.mjs'); process.exit(1); }
  console.log('deferral_parity.json: identical to what the generator produces (' + bytes.length.toLocaleString() + ' bytes)');
} else {
  fs.writeFileSync(FILE, bytes);
  const by = {}; out.scenarios.forEach(s => { by[s.kind || 'random'] = (by[s.kind || 'random'] || 0) + 1; });
  console.log('fixtures:', by, 'bytes', bytes.length);
}
process.exit(0);
