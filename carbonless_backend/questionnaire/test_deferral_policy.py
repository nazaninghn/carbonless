"""Which questions may be left for later ("I don't know — answer later"), enforced by the SERVER.

The frontend hides the button for a question that cannot be deferred, but the server is the authority: this
module pins the policy (deferral_policy.json, generated from the questionnaire catalogue), the route walk the
policy relies on (shared fixtures with the frontend engine), and the endpoints: a required question is refused,
a deferrable one is accepted and listed, a conditional one follows its condition, a deferred question the
answers have taken off the route is not pending any more, and completion is refused while a required
question is unanswered. Nothing here calculates anything, and no saved answer is ever touched.
"""
import json
from pathlib import Path

from django.contrib.auth.models import User
from rest_framework.test import APIClient

from companies.models import Company, CompanyMembership
from . import deferral
from . import tests as _base
from .carboniq_validation import is_known_step
from .models import CarbonReport, ReportStep

HERE = Path(__file__).parent


class PolicyInvariantTests(_base.TestCase):
    """The classification is consistent with what the questions do."""

    def test_every_question_is_classified_and_known_to_the_server(self):
        Q = deferral.policy()
        self.assertEqual(len(Q), 178)
        self.assertEqual([i for i in Q if not is_known_step(i)], [])        # nothing the server would not accept
        self.assertTrue({q['kind'] for q in Q.values()} <= {'required', 'deferrable', 'conditional', 'info'})

    def test_a_question_that_routes_the_questionnaire_is_never_deferrable(self):
        for qid, q in deferral.policy().items():
            if q.get('nbv') and q['kind'] != 'info':
                self.assertEqual(deferral.effective_kind(q), 'required', qid)

    def test_loop_items_the_boundary_the_method_and_the_sign_off_are_required(self):
        Q = deferral.policy()
        for qid, q in Q.items():
            if q.get('loop'):
                self.assertEqual((deferral.effective_kind(q), q['code']), ('required', 'loop_item'), qid)
        for qid in ('A1', 'A3', 'A4', 'B1', 'C1', 'C3', 'D1', 'D3', 'D4', 'SCOPE-GROUPING', '2A-1', '2B-OC1', '2B-OC1a',
                    '2B-OC2', '2B-FC1', '2B-FC2', '2B-EQ1', '3A-1', '3B-1', '3C-1', '3D-0', '4B-1', 'K3C1-1',
                    'K3C3-INFO', 'K3C7-0', '6F-3', '7C-2'):
            self.assertEqual(deferral.effective_kind(Q[qid]), 'required', qid)

    def test_profile_documentation_and_data_follow_ups_are_deferrable(self):
        Q = deferral.policy()
        for qid in ('A2', 'A5', 'A6', 'A7b', 'B2', 'B3', 'B4', 'B5', 'B6', '2C-1', '2C-2', '2C-3', '3A-EF-a',
                    '4A-EF-a', 'K3C2-1', 'K3C8-1', 'K3C15-1', '6A-1a', '6C-2', '6E-1'):
            self.assertEqual(deferral.effective_kind(Q[qid]), 'deferrable', qid)
        self.assertEqual(Q['2C-1']['kind'], 'conditional')                    # only when 2B-OC1 = no

    def test_scope_grouping_question_36_is_required_because_it_decides_the_route(self):
        q = deferral.policy()['SCOPE-GROUPING']
        self.assertEqual((q['n'], q['kind'], q['code']), (36, 'required', 'structure'))
        self.assertTrue(q['req'])

    def test_the_policy_counts(self):
        kinds = {}
        for q in deferral.policy().values():
            k = q['kind'] + ('>' + q['then'] if q.get('then') else '')
            kinds[k] = kinds.get(k, 0) + 1
        self.assertEqual(kinds, {'required': 33, 'deferrable': 10, 'conditional>deferrable': 49, 'info': 12,
                                 'conditional>required': 74})


class RouteParityTests(_base.TestCase):
    """The server walks the same route as the questionnaire (fixtures generated by the frontend engine)."""

    def test_the_route_the_pending_list_and_the_decisions_match_the_frontend_engine(self):
        data = json.load(open(HERE / 'deferral_parity.json', encoding='utf-8'))['scenarios']
        self.assertGreaterEqual(len(data), 100)
        for i, s in enumerate(data):
            self.assertEqual(deferral.route_ids(s['answers']), s['route'], f'route #{i}')
            self.assertEqual(deferral.route_ids(s['answers'], confirmed=True), s['confirmed_route'], f'confirmed #{i}')
            self.assertEqual(deferral.active_pending(s['pending'], s['answers']), s['active_pending'], f'pending #{i}')
            self.assertEqual(deferral.required_unanswered(s['answers']), s['required_unanswered'], f'required #{i}')
            if s.get('kind') == 'complete':      # a route the questionnaire can finish: the server never finds a required question open
                self.assertEqual(s['required_unanswered'], [], f"complete route {s['label']}")
                self.assertEqual(deferral.route_ids(s['answers'])[-1], '7B-INFO')
            for qid, want in s['defer'].items():
                ok, code = deferral.defer_status(qid, s['answers'])
                self.assertEqual('ok' if ok else code, want, f'defer {qid} #{i}')


class DeferralEndpointTests(_base.TestCase):

    def setUp(self):
        self.user = User.objects.create_user('df_owner', 'df_owner@test.com', 'pass12345')
        self.company = Company.objects.create(
            legal_entity_name='Deferral Co', tax_number='81', country_of_headquarters='TR', countries_of_operation='TR',
            nace_code='', main_activity_description='x', number_of_employees='1-10', annual_turnover_range='x',
            number_of_facilities=1)
        CompanyMembership.objects.create(user=self.user, company=self.company, role='owner')
        self.report = CarbonReport.objects.create(company=self.company, created_by=self.user, reporting_year=2025)
        self.client = APIClient()
        self.client.force_authenticate(self.user)

    def _put(self, step, answer):
        ReportStep.objects.update_or_create(report=self.report, step_id=step, defaults={'answer': answer})

    def _answer_the_gates(self, **override):
        """The user has answered every yes/no and summary gate, as a user who reaches a late question has:
        'no' where there is one, else the first choice. `override` replaces some (step id, '-' written as '_')."""
        for qid, q in deferral.policy().items():
            if q.get('nbv') and q['kind'] != 'info' and q['type'] not in ('section_picker', 'multi_select'):
                self._put(qid, {'answer': 'no' if 'no' in q['nbv'] else next(iter(q['nbv']))})
        self._put('A7', {'has_previous_report': False})
        for k, v in override.items():
            self._put(k.replace('_', '-'), {'answer': v})

    def _mark(self, step, lang='en', pending=True):
        return self.client.post(f'/api/questionnaire/{self.report.id}/pending/',
                                {'step': step, 'pending': pending, 'language': lang}, format='json')

    def _status(self):
        r = self.client.get(f'/api/questionnaire/{self.report.id}/')
        self.assertEqual(r.status_code, 200, r.content)
        return r.data

    def _snapshot(self):
        return (sorted(ReportStep.objects.filter(report=self.report).values_list('step_id', 'answer', 'is_skipped')),
                CarbonReport.objects.filter(pk=self.report.pk).values_list(
                    'status', 'current_step', 'client_progress', 'reporting_year').get())

    # A. REQUIRED
    def test_required_questions_cannot_be_deferred(self):
        for step, reason in (('SCOPE-GROUPING', 'structure'), ('3A-0', 'gate'), ('A4', 'identity'), ('D3', 'boundary'),
                             ('D1', 'methodology'), ('2A-1', 'loop_source'), ('A3', 'calc_prerequisite')):
            r = self._mark(step)
            self.assertEqual(r.status_code, 400, (step, r.content))
            self.assertEqual((r.data['code'], r.data['reason']), ('not_deferrable', reason), step)
            self.assertIn('cannot be left for later', r.data['error_en'])
            self.assertIn('sonraya bırakılamaz', r.data['error_tr'].lower())
        self.assertEqual(self._status()['pending_questions'], [])
        self.assertFalse(CarbonReport.objects.get(pk=self.report.pk).pending_questions)
        self.assertFalse(ReportStep.objects.filter(report=self.report).exists())      # and nothing was invented

    def test_a_late_gate_is_required_too_once_its_route_is_reached(self):
        self._answer_the_gates(**{'4A_0': 'yes'})
        for step in ('4A-EF', 'K3C1-0'):                       # one gate at a time: the route stops at the first unanswered
            ReportStep.objects.filter(report=self.report, step_id=step).delete()
            r = self._mark(step)
            self.assertEqual((r.status_code, r.data['code'], r.data['reason']), (400, 'not_deferrable', 'gate'), step)
            self._put(step, {'answer': 'no'})

    def test_a_loop_item_a_sign_off_and_an_info_screen_cannot_be_deferred(self):
        for step, reason in (('2A-2', 'loop_item'), ('7C-2', 'sign_off'), ('3-GİRİŞ', 'info')):
            r = self._mark(step)
            self.assertEqual((r.status_code, r.data['reason']), (400, reason), step)

    def test_the_refusal_follows_the_language(self):
        self.assertIn('sonraya bırakılamaz', self._mark('SCOPE-GROUPING', lang='tr').data['error'].lower())
        self.assertIn('cannot be left for later', self._mark('SCOPE-GROUPING', lang='en').data['error'])

    # B. DEFERRABLE
    def test_deferrable_questions_can_be_deferred_and_are_listed_without_any_answer(self):
        self._answer_the_gates()
        for step in ('A2', 'B2', 'K3C7-4'):
            r = self._mark(step)
            self.assertEqual(r.status_code, 200, (step, r.content))
        self.assertEqual(self._status()['pending_questions'], ['A2', 'B2', 'K3C7-4'])
        self.assertFalse(ReportStep.objects.filter(report=self.report, step_id__in=['A2', 'B2', 'K3C7-4']).exists())

    def test_a_deferrable_question_beyond_an_unanswered_gate_does_not_apply_yet(self):
        # nothing answered: the route is only known as far as the first gate (A7)
        self.assertEqual(self._mark('A2').status_code, 200)                              # before it: fine
        r = self._mark('K3C7-4')
        self.assertEqual((r.status_code, r.data['code']), (409, 'not_applicable'))

    # C. CONDITIONAL
    def test_a_conditional_question_follows_its_condition(self):
        self._answer_the_gates(**{'4A_0': 'yes', '4A_EF': 'no'})
        r = self._mark('4A-EF-a')
        self.assertEqual((r.status_code, r.data['code']), (409, 'not_applicable'))       # the supplier declaration: no
        self._put('4A-EF', {'answer': 'yes'})
        r = self._mark('4A-EF-a')                                                         # now it applies, deferrable
        self.assertEqual(r.status_code, 200, r.content)
        self.assertEqual(r.data['pending_questions'], ['4A-EF-a'])

    def test_a_conditional_required_question_is_required_only_when_it_applies(self):
        self._answer_the_gates()
        self.assertEqual(self._mark('2B-OC2').data['code'], 'not_applicable')           # needs operational control + yes
        self._put('D3', {'boundary_approach': 'operational_control'})
        self._put('2B-OC1', {'answer': 'yes'})
        r = self._mark('2B-OC2')
        self.assertEqual((r.status_code, r.data['code'], r.data['reason']), (400, 'not_deferrable', 'boundary'))

    def test_phase_one_answers_stored_under_named_fields_drive_the_route(self):
        self._put('A7', {'has_previous_report': False})
        self.assertEqual(self._mark('A7a').data['code'], 'not_applicable')
        self._put('A7', {'has_previous_report': True})
        self.assertEqual(self._mark('A7a').status_code, 200)                              # baseline year: only after "yes"

    # pending list / inactive questions
    def test_a_deferred_question_the_answers_take_off_the_route_is_not_pending_any_more(self):
        self._answer_the_gates(**{'4A_0': 'yes', '4A_EF': 'yes'})
        self.assertEqual(self._mark('4A-EF-a').status_code, 200)
        self.assertEqual(self._status()['pending_questions'], ['4A-EF-a'])
        self._put('4A-EF', {'answer': 'no'})                                              # the user changes the gate
        self.assertEqual(self._status()['pending_questions'], [])                         # inactive: not pending
        self.assertEqual(deferral.pending_to_show(CarbonReport.objects.get(pk=self.report.pk)), [])

    # completion
    def test_the_inventory_cannot_be_completed_while_a_required_question_is_unanswered(self):
        r = self.client.patch(f'/api/questionnaire/{self.report.id}/step/',
                              {'step': '7B-INFO', 'data': {'answer': 'done'}}, format='json')
        self.assertEqual(r.status_code, 400, r.content)
        self.assertEqual(r.data['code'], 'required_unanswered')
        self.assertIn('A1', r.data['required_unanswered'])
        self.assertIn('SCOPE-GROUPING', r.data['required_unanswered'])
        self.assertNotEqual(CarbonReport.objects.get(pk=self.report.pk).status, CarbonReport.Status.COMPLETED)

    def test_a_deferred_question_still_blocks_completion_until_it_is_answered(self):
        self.assertEqual(self._mark('A2').status_code, 200)
        r = self.client.patch(f'/api/questionnaire/{self.report.id}/step/',
                              {'step': '7B-INFO', 'data': {'answer': 'done'}}, format='json')
        self.assertEqual(r.data['code'], 'pending_questions')
        self.assertEqual(r.data['pending_questions'], ['A2'])

    # saved answers
    def test_saved_answers_and_progress_are_untouched_by_deferring_and_refusals(self):
        self._answer_the_gates()
        self._put('B1', {'nace_code': 'C', 'nace_label': 'Manufacturing'})
        before = self._snapshot()
        for step in ('A2', 'K3C7-4', 'SCOPE-GROUPING', '3A-0', 'D3', '4A-EF-a'):
            self._mark(step)
        self._mark('A2', pending=False)
        self.assertEqual(self._snapshot(), before)
